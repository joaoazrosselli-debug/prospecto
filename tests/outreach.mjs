import assert from 'node:assert/strict';
import {outreachQueue,outreachMessage} from '../public/outreach.js';
import {normalizeLead,summarize,createSite,checklist} from '../public/core.js';
const phone='41998765432',number='5541998765432';
const real=(id,patch={})=>normalizeLead({id,name:'Empresa '+id,phone,city:'Curitiba / PR',outreach:{qualified:true,permission:'allowed',permissionSource:'Pediu a proposta pelo formulário.',permissionNumber:number},...patch});
assert.equal(outreachQueue([real('a')])[0].ready,true);
assert.equal(outreachQueue([real('a',{isTest:true})])[0].ready,false);
assert.equal(summarize([real('a',{isTest:true,stage:'fechado',value:1000,received:900})]).received,0);
assert.equal(outreachQueue([real('a',{businessPhone:phone,phone:''})])[0].ready,false);
assert.equal(outreachQueue([real('a',{contactAllowed:true,outreach:{qualified:true}})])[0].ready,false);
assert.equal(outreachQueue([real('a',{outreach:{qualified:true,permission:'allowed',permissionNumber:number}})])[0].ready,false);
assert.equal(outreachQueue([real('a',{phone:'41988776655'})])[0].ready,false);
assert.deepEqual(outreachQueue([real('b'),real('a')]).map(r=>[r.leadId,r.ready]),[['a',true],['b',false]]);
assert.equal(outreachQueue([real('a'),real('b',{outreach:{permission:'blocked',permissionNumber:number}})]).some(r=>r.ready),false);
assert.equal(outreachQueue([real('a'),real('b',{isTest:true,outreach:{permission:'blocked',permissionNumber:number}})])[0].ready,true);
assert.equal(outreachQueue([real('a'),real('b',{stage:'contato'})]).some(r=>r.ready),false);
assert.equal(outreachQueue([real('a'),real('b',{outreach:{lastContactAt:new Date().toISOString()}})]).some(r=>r.ready),false);
assert.match(outreachMessage(real('a'),{}),/estudante de Engenharia/);
assert.ok(!outreachMessage(real('a'),{}).includes('não tem site'));
assert.match(outreachMessage(real('a'),{salesProfile:'studio',studio:'J Studio',senderName:'João'}),/João, do J Studio/);
const noWhats=real('a',{phone:'',businessPhone:phone});
assert.equal(checklist(noWhats).find(([label])=>label==='Contato para a página')[1],true);
assert.ok(createSite(noWhats).includes('tel:+'+number));
assert.ok(!createSite(noWhats).includes('wa.me'));
const generated={...real('a'),assets:[{id:'image',role:'hero',mime:'image/webp'}],research:{media:[{assetId:'image',usage:'generated'}]}};
assert.equal(checklist(generated).find(([label])=>label==='Fotos do negócio')[1],false);

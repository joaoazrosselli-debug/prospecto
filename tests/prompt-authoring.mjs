import assert from 'node:assert/strict';
import {normalizeLead} from '../public/core.js';
import {createPrompt,createSite} from '../public/landing.js';
import {creativeDirection,chatAuthoringRequest} from '../public/creative-direction.js';
const base={id:'qa-direction',name:'Exemplo de teste',city:'Curitiba / PR',notes:'SEGREDO_INTERNO_8F3',value:912345.67,received:456789.12,publicEnabled:false};
const laundry=normalizeLead({...base,sector:'Lavanderia',brandStyle:'Marca próxima, fotos reais, evitar branco clínico.'});
const tech=normalizeLead({...base,id:'qa-tech',sector:'Eletrônicos e assistência técnica'});
const food=normalizeLead({...base,id:'qa-food',sector:'Confeitaria e kits de festa'});
const pet=normalizeLead({...base,id:'qa-pet',sector:'Pet shop e banho e tosa'});
assert.equal(creativeDirection(laundry).key,'laundry');
assert.equal(creativeDirection(tech).key,'technology');
assert.equal(creativeDirection(food).key,'food');
assert.equal(creativeDirection(pet).key,'pet');
assert.equal(creativeDirection(normalizeLead({...base,sector:'Comércio local'})).key,'general');
assert.notDeepEqual(creativeDirection(laundry).colors,creativeDirection(tech).colors);
const prompt=createPrompt(laundry,{});
assert.ok(prompt.includes(laundry.brandStyle));
assert.ok(prompt.includes('DIREÇÃO CRIATIVA DESTE CLIENTE'));
assert.ok(prompt.includes('Cuidado cotidiano, com leveza'));
assert.ok(!prompt.includes(base.notes)&&!prompt.includes(String(base.value))&&!prompt.includes(String(base.received)));
assert.ok(prompt.length<50000);
const literal='Instrução personalizada literal: $& {{dados_empresa}} {{midias}}';
assert.equal(createPrompt({...laundry,promptOverride:literal},{}),literal);
assert.notEqual(createPrompt({...laundry,promptOverride:literal},{},{ignoreOverride:true}),literal);
const custom=createPrompt(laundry,{promptTemplate:'PRESERVAR TEMPLATE DO ESTÚDIO\n{{dados_empresa}}'});
assert.ok(custom.startsWith('PRESERVAR TEMPLATE DO ESTÚDIO'));
assert.ok(custom.includes('Cuidado cotidiano, com leveza')&&custom.includes('MATERIAIS'));
const literalData=createPrompt({...laundry,description:'Manter literal {{midias}} e {{direcao_criativa}}.'},{});
assert.ok(literalData.includes('Manter literal {{midias}} e {{direcao_criativa}}.'));
const withMedia={...laundry,assets:[{id:'image-1',name:'imagem.png',mime:'image/png',role:'hero',alt:'Referência para estudar',url:'https://private.example/DO_NOT_EXPORT_TOKEN'}],research:{missing:['Confirmar horários com a empresa'],media:[{assetId:'image-1',usage:'reference',sourceUrl:'https://example.com/referencia'}]}};
const mediaPrompt=createPrompt(withMedia,{});
assert.ok(mediaPrompt.includes('Referência; autorização para publicar pendente'));
assert.ok(mediaPrompt.includes('midias/image-1.png')&&!mediaPrompt.includes('DO_NOT_EXPORT_TOKEN'));
assert.ok(mediaPrompt.includes('Confirmar horários com a empresa'));
const before=createSite(laundry),after=createSite({...laundry,brandStyle:'Nova direção, sem alterar a página pronta.'});
assert.equal(before,after);
const readyHTML='<!doctype html><html><body><h1>Versão aprovada</h1></body></html>';
assert.equal(createSite({...laundry,customHtml:readyHTML}),readyHTML);
assert.ok(chatAuthoringRequest(laundry,prompt).includes(laundry.id));
assert.ok(chatAuthoringRequest({...laundry,isDemo:true},prompt).includes('empresa fictícia'));
assert.ok(!chatAuthoringRequest({...laundry,isDemo:true},prompt).includes('prospecto_save_draft'));
console.log('PASS: rotas visuais por segmento e preferências do cliente, sem expor notas ou valores internos.');
console.log('PASS: prompts personalizados literais e templates existentes preservados; inserções em passagem única.');
console.log('PASS: procedência de mídia, pendências e caminhos do kit, sem exportar URLs privadas.');
console.log('PASS: modelos e HTMLs existentes preservados; pedidos ao chat distinguem demonstração e ficha real.');
